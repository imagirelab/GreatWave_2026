"""FLIP54 K54: write the cfg of one K54 2D strip and its pre-run checks (py -3.10 -B; numpy + scipy for the Fenton table; < 1 min).
2026-10-18 written new (Claude, FLIP54 builder K) by adapting flip49/g49_pcfg.py (make / parms_for / drift_parms / precheck) and
flip49/g49_planB.py (make_strip / precheck_B / ledge_bed_checks) to the D19B strip with the two-slope bed and an exit sponge. Those files are
FROZEN (read only); nothing of FLIP49-FLIP53 is edited.

One strip = a quasi-2D slab (half width 6 m, dp 0.5 m, grid 1 m) of the D19B tank (box 412 m, flat 19 m, 1:10 from x 160.25 m) whose bed
leaves the 1:10 at h pg_hL with a 1:pg_s2 part onto a shelf_h terrace (K0 / K0p / A12: 1:10 straight onto the 7.0 m shelf), a periodic
Fenton stream-function wave (T 9.33 s; A12 T 12 s) generated by the FLIP49 inlet band (0-100 m, ramp 2 T, x_p 80 m), an exit sponge over
the shelf (332-412 m, sigma 1.41, chi^2; 1D reflection <= 0.07 [computed]), drift stage A (whole-tank volume held in x 110-327 m, as DFG-2B
and DM1A), 90 s, records: hf + centre section r2 every frame, r6 gauges / levels; no r4 / r5 (2D: the section is the whole wave).

usage:
  py -3.10 -B g54_pcfg.py selfcheck                      bed_selfcheck of every arm, sponge reflection, H rules (json to stdout; writes nothing)
  py -3.10 -B g54_pcfg.py tables                         write the two Fenton tables the scene check probes (k54/tables; json paths)
  py -3.10 -B g54_pcfg.py cfg <arm>                       write Unity/Build/FLIP54/k54/strips/ready/<run_id>.json (precheck inside; refuses
                                                          if not ok). H by the registered rule: K0p = H_GUESS; K0 / K1-K5 = the calibrated
                                                          H_K0 (k54/plan/calibration_K0.json); A12 = H_K0 x Goda ratio
  py -3.10 -B g54_pcfg.py dry [--out=<dir under FLIP54>]  dry build of EVERY arm at the pilot H (A12 at its rule from the pilot H) into
                                                          Unity/Build/FLIP54/_scratch/dry_k54/ (cfgs + summary), no hython; checks that the
                                                          cfgs are complete and every precheck item except the calibration passes
Prints one JSON line (the cfg path, run id, precheck ok / reason) last.
"""
