STRIP_S_PER_MPF = 758.0 / (315612 * 2881) * 1e6   # s per million particles per frame: FLIP49 S1_axis_PG12s_stC (758 s, 315,612 max particles,
                                                   # 2881 frames, r5 every 2nd frame from 24 s) [measured]; K54 writes no r5 -> an upper bound
GROWTH_HI = 1.45                                   # particle growth up to x1.45 over a strip (FLIP49 S1 strips x1.41-1.47) [measured]
WALL_LIMIT = 1740.0
KR_MAX = 0.10                                      # task: exit sponge so Kr <= 0.1


def ramp_of(T):
    return C.RAMP_PERIODS * float(T)


def sf_table(T, H):
    """the Fenton table at h0 19 m (py -3.10, scipy); cached as json in k54/tables (hython reads tables from the cfg)."""
    p = C.table_file(T, H)
    if os.path.exists(p):
        tb = json.load(open(p, encoding="utf8"))
        if abs(float(tb["h"]) - C.H0) < 1e-12 and abs(float(tb["T"]) - float(T)) < 1e-9 and abs(float(tb["H"]) - float(H)) < 1e-9:
            return tb
    _, tb = C.sf_solve(C.H0, float(T), float(H), C.SF_N)
    C.jdump(tb, p)
    return tb


