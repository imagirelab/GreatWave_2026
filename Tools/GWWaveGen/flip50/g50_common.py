    out = {}
    for nm in ("g50_common.py", "g50_dirfield.py", "g50_table.py", "g50_tanklib.py", "g50_build_tank.py", "x50_build.py", "g50_run.py", "g50_chain.py",
               "g50_pcfg.py", "g50_ana.py", "g50_video.py", "g50_planD.py"):
        p = os.path.join(TOOLS, nm)
        out["flip50/" + nm] = sha256_file(p)[:16] if os.path.exists(p) else None
    for nm in ("g49_common.py", "g49_tanklib.py", "g49_run.py", "g49_chain.py", "g49_periodic_ana.py", "g49_video2.py"):
        p = os.path.join(TOOLS49, nm)
        out["flip49/" + nm] = sha256_file(p)[:16] if os.path.exists(p) else None
    for nm in ("g48_common.py", "g48_tanklib.py", "g48_analyze.py", "g48_peak_metrics.py", "g48_video2.py"):
        p = os.path.join(TOOLS48, nm)
