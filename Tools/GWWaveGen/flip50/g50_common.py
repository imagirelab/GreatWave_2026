def sf_descriptor(T, H_ref, note=None):
    """cfg['sf'] for the D 3D runs: a LINEAR DESCRIPTOR of the directional sea (period, linear wavelength at h0) read by g50_run (period of the
    drift stage C mean) and by g49_periodic_ana / g49_video2 (T, L for the crest window, c, k). It is NOT a forcing table (sf_on 0, B = 0)."""
    import numpy as np
    om = 2 * math.pi / float(T)
    k = om * om / G
    for _ in range(80):
        th = math.tanh(k * H0)
        k = k - (G * k * th - om * om) / (G * th + G * k * H0 * (1 - th * th))
    L = 2 * math.pi / k
    return dict(descriptor=True, kind="linear descriptor of the directional sea at h0 (NOT a forcing table; sf_on 0)",
                h=H0, T=float(T), H=float(H_ref), N=1, k=float(k), L=float(L), c=float(L / float(T)), Ubar=0.0, B=[0.0], E=[0.0, 0.0],
                H_note="H = linear target wave height at the first centre gauge (x 110 m, y 0.5 m); each gauge has its own target (dir.gauges_lin)",
                note=note or "")


def redirect_gc49():
    """For the analysis / video wrappers only (py -3.10): make the FLIP49 read-only modules write inside Unity/Build/FLIP50 and know layout D.
    Patches the in-memory g49_common module (never the file): B49 -> B50 (guard_out49, A46.B46 and the video cache follow), LAYOUTS['D'],
    module_shas. PLAN_FROZEN stays FLIP49's plan_frozen.json (PER thresholds are report-only, as for plan A). Call BEFORE importing
    g49_periodic_ana or g49_video2."""
    GC49.B49 = B50
    GC49.LAYOUTS["D"] = LAYOUT_D
    GC49.module_shas = module_shas
    return GC49


