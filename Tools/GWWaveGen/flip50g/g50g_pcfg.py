UNPATCHED_REGEN = r'''
import sys, json, os
sys.dont_write_bytecode = True
sys.path.insert(0, r"%s")
import g50_pcfg as PC
out = {}
for nm, st, rel in %r:
    c = PC.preset(nm, {"stage": st})
    p = os.path.join(r"%s", os.path.basename(rel))
    open(p, "w", encoding="utf8").write(json.dumps(c, indent=1, ensure_ascii=False, default=float))
    out[rel] = p
print(json.dumps(out))
'''


def regen_existing(out_dir):
    """the six existing cfgs regenerated (a) in a fresh unpatched py -3.10 process and (b) here under the groove patch; byte comparison."""
    res = {}
    d_un = os.path.join(out_dir, "regen_unpatched"); d_pa = os.path.join(out_dir, "regen_patched")
    os.makedirs(d_un, exist_ok=True); os.makedirs(d_pa, exist_ok=True)
    code = UNPATCHED_REGEN % (GG.TOOLS50, EXISTING, d_un)
    r = subprocess.run([sys.executable, "-B", "-c", code], capture_output=True, text=True, encoding="utf8")
    if r.returncode != 0:
        raise SystemExit("unpatched regeneration failed: %s" % r.stderr[-1500:])
    for nm, st, rel in EXISTING:
        c = PC.preset(nm, {"stage": st})
        pp = os.path.join(d_pa, os.path.basename(rel))
        open(pp, "w", encoding="utf8").write(json.dumps(c, indent=1, ensure_ascii=False, default=float))
        ready = open(os.path.join(GC.B50, rel), "rb").read()
        bu = open(os.path.join(d_un, os.path.basename(rel)), "rb").read()
        bp = open(pp, "rb").read()
        res[rel] = dict(ready_sha16=hashlib.sha256(ready).hexdigest()[:16], unpatched_sha16=hashlib.sha256(bu).hexdigest()[:16],
                        patched_sha16=hashlib.sha256(bp).hexdigest()[:16], unpatched_equal=bool(bu == ready), patched_equal=bool(bp == ready))
    return res


def check():
    t0 = time.time()
    out = dict(date=time.strftime("%Y-%m-%d %H:%M:%S"), tool="flip50g/g50g_pcfg.py check", dg1=GG.frozen_ref())
    out["self_checks"] = GG.self_checks()
    out["readings"] = dict(zip(("readings", "source"), GG.readings()))
    out["regen_existing"] = regen_existing(GG.SCRATCH)
    out["regen_all_equal"] = bool(all(v["unpatched_equal"] and v["patched_equal"] for v in out["regen_existing"].values()))
    out["untouched"] = GG.check_untouched()
    dg = {}
    for which in ("SMOKE_DG1", "DG1"):
        c, b0, diff = build_cfg(which)
        p = out_path(c)
        dg[which] = dict(run_id=c["run_id"], precheck_ok=c["precheck"]["ok"], reason=c["precheck"]["reason"], particles_model=c["precheck"]["particles_model"],
                         key_diff=diff, written=os.path.exists(p),
                         written_equal=bool(os.path.exists(p) and open(p, "rb").read() == dumps_file(c)))
    out["dg1_cfgs"] = dg
    out["seed_model_dp1"] = seed_model(1.0)
    out["order_state"] = GG.order_state()
    out["ok_code"] = bool(out["regen_all_equal"] and out["untouched"]["ok"] and all(v["precheck_ok"] for v in dg.values()))
    out["ok_self_checks"] = bool(out["self_checks"]["ok"])
    out["cpu_s"] = round(time.time() - t0, 2)
    p = os.path.join(GG.SCRATCH, "pcfg_check_g.json")
    os.makedirs(GG.SCRATCH, exist_ok=True)
    json.dump(out, open(p, "w", encoding="utf8"), indent=1, ensure_ascii=False, default=str)
    return out, p


def seed_model(dp):
    """numpy seeding model of the smoke core box (no Houdini): what gate b reads if Houdini seeds exactly the groove lattice (no jitter)."""
    xs = (np.arange(int(round(GC.LX / dp))) + 0.5) * dp
    ys = (np.arange(int(round(GC.W_MAIN / dp))) + 0.5) * dp
    X, Y = np.meshgrid(xs, ys, indexing="ij")
    spec = dict(GC.SPEC_D19B, **GG.SPEC_GR_ON)
    bg = GC.bed_z(X, Y, **spec)
    zl = GG.lattice_low(bg, dp)
    m = (X >= 265.0) & (X <= 315.0) & (Y >= 5.0) & (Y <= 20.0)
    Pp = np.c_[X[m], zl[m], Y[m]]
    return GG.seed_core_stats(Pp, dp, spec)



def main(argv):
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass
    opt = {a[2:].split("=", 1)[0]: (a.split("=", 1)[1] if "=" in a else "1") for a in argv if a.startswith("--")}
