def dumps_file(c):
    """the bytes g50_pcfg.write produces (json.dump into a Windows text-mode file: CRLF)."""
    return json.dumps(c, indent=1, ensure_ascii=False, default=float).replace("\n", os.linesep).encode("utf8")


def load_base(base):
    raw = open(base["path"], "rb").read()
    s16 = hashlib.sha256(raw).hexdigest()[:16]
    if s16 != base["sha16"]:
        raise SystemExit("base cfg %s sha256_16 %s differs from the frozen %s" % (base["path"], s16, base["sha16"]))
    return json.loads(raw.decode("utf8"))


def amendment_text(kind):
    return ("AM-D20 (Unity/Build/FLIP50/plan/amendments.jsonl; rules in Unity/Build/FLIP50/plan/dg1_frozen.json sha256 %s): D round 3 = DG1 "
            "(user Q80), one change from %s = the bed (the frozen groove pair); drift stage A of AM-D18 kept; plan_D_frozen.json criteria and "
            "thresholds unchanged; Q80 criteria S0-S4 and the stop rule frozen in dg1_frozen.json" % (GG.DG1_SHA256[:16], "DM1A" if kind == "main" else "SMOKE50DA"))


def build_cfg(which):
    fz = GG.frozen()
    main = which == "DG1"
    base = GG.BASE_MAIN if main else GG.BASE_SMOKE
    b0 = load_base(base)
    c = copy.deepcopy(b0)
    c["run_id"] = GG.RUN_MAIN if main else GG.RUN_SMOKE
    cs = c["case"]
    cs.pop("rerun_of", None)
    cs["name"] = "FLIP50_3d_D19Bgr_DG1" if main else "FLIP50_smoke_D19Bgr_DG1"
    cs["queue_id"] = "DG1" if main else "SMOKE50DG1"
    if main:
        cs["d_round"] = 3
    cs["amendment"] = amendment_text("main" if main else "smoke")
    cs["baseline"] = base["run_id"]
    cs["dg1_frozen"] = GG.DG1_FROZEN_REL
    cs["dg1_frozen_sha256"] = GG.DG1_SHA256
    c["parms"].update(GG.SPEC_GR_ON)
    spec = dict(GC.SPEC_D19B, **GG.SPEC_GR_ON)
    c["bed"] = GC.bed_record(spec, c["box"])
    if main:
        c["note"] = ("FLIP50 option D DG1 (round 3, AM-D20, user Q80; the last D round): DM1A unchanged (3D dp 0.5, half tank W 140 with a 45 m side "
                     "band, directional sea T 12 s, +-80 deg, 30 equal components, a_sum 6.331 m, focus (220.25, 0), stage A (AM-D18), 92 s, heavy "
                     "records continuously from 44 s every 3 frames) except ONE change, the bed: %s. Groove hip %s (flip50g tools); Q80 criteria "
                     "S0-S4 and the stop rule frozen in %s" % (GROOVE_TXT, GG.HIP_G_REL, GG.DG1_FROZEN_REL))
    else:
        c["note"] = ("FLIP50 option D DG1 smoke (never judged): SMOKE50DA unchanged (3D dp 1.0, W 140, DM1 sea T 12 s +-80 deg, stage A (AM-D18), 0-50 s, "
                     "one launch of <= 29 min) except the bed: %s. Frozen smoke gates as SMOKE50DA plus the DG1 gates of dg1_frozen.json smoke "
                     "(inlet / side mean ratio within 0.03 of SMOKE50DA, groove hip sha and CTRL gr_*, frame-1 particles against the numpy groove bed)"
                     % GROOVE_TXT)
    c["hip"] = GG.HIP_G_REL
    c["build_check"] = GG.BUILD_CHECK_G_REL
    c.pop("precheck", None)
    c["precheck"] = precheck_g(c)
    diff = key_diff(b0, c)
    return c, b0, diff


def precheck_g(c):
    """g50_pcfg.precheck under the groove patch, with the D19B-only items replaced (cfg_rule: bed item, particles_model, water_m3, time)."""
    o = PC.precheck(c)
    P = c["parms"]
    spec = GC.bed_spec(c)
    key = ("3d", float(P["dp"]))
    n = o["particles_model"]
    n0 = GC.count_particles({k: v for k, v in spec.items() if not k.startswith("gr_")}, float(P["Lx"]), float(P["W"]), float(P["dp"]),
                            zb=float(P["zb"]), bed_gap=float(P["bed_gap"]))[0]
    new = {}
    for k, v in o["checks"].items():
        if k == "bed_is_D19B":
            new["bed_is_D19B_plus_frozen_groove"] = bool(
                all((spec.get(kk) == vv) if not isinstance(vv, float) else abs(float(spec.get(kk)) - vv) < 1e-12 for kk, vv in GC.SPEC_D19B.items())
                and not GC.is_new(spec) and spec.get("k_end") is None and GG.groove_of(spec) == GG.GR
                and (c.get("bed") or {}).get("groove") == GG.frozen_parameters() and GG.cfg_groove_ok(c) == [])
        elif k == "particles_as_designed":
            new[k] = bool(EXPECT_G.get(key) == n and EXPECT_D19B.get(key) == n0)
        else:
            new[k] = v
    new["dg1_frozen_sha"] = bool(GG.sha256_file(GG.DG1_FROZEN) == GG.DG1_SHA256)
    o["checks"] = new
    o["particles_model_D19B"] = int(n0)
    o["particles_added_by_groove"] = int(n - n0)
    o["tags"] = dict(o.get("tags") or {}, particles="computed (numpy, the scene's seeding rule, D19B + the frozen groove bed through g50g_common)")
    o["ok"] = bool(all(new.values()))
    o["reason"] = None if o["ok"] else "failed: " + ", ".join(k for k, v in new.items() if not v)
    return o


def key_diff(b0, c):
    """the key-level difference against the base cfg; raises unless it is exactly the cfg_rule list."""
    top_changed = sorted(k for k in set(b0) | set(c) if b0.get(k, None) != c.get(k, None))
    top_added = sorted(set(c) - set(b0)); top_removed = sorted(set(b0) - set(c))
    cs0, cs1 = b0["case"], c["case"]
    case_changed = sorted(k for k in set(cs0) | set(cs1) if cs0.get(k, "\0") != cs1.get(k, "\0"))
    p0, p1 = b0["parms"], c["parms"]
    parms_changed = sorted(k for k in p0 if p0[k] != p1.get(k, "\0"))
    parms_added = [k for k in p1 if k not in p0]
    bd0, bd1 = b0["bed"], c["bed"]
    bed_changed = sorted(k for k in set(bd0) | set(bd1) if bd0.get(k, "\0") != bd1.get(k, "\0"))
    d = dict(top_changed=top_changed, top_added=top_added, top_removed=top_removed, case_changed=case_changed, parms_changed=parms_changed,
             parms_added=parms_added, bed_changed=bed_changed, bed_order_kept=list(bd1)[:len(bd0)] == list(bd0),
             parms_order_kept=list(p1)[:len(p0)] == list(p0), top_order_kept=[k for k in c if k in b0] == list(b0))
    bad = []
    if set(top_changed) - ALLOWED_TOP:
        bad.append("top-level keys changed outside the cfg_rule: %s" % sorted(set(top_changed) - ALLOWED_TOP))
    if top_removed or set(top_added) - {"hip", "build_check"}:
        bad.append("top-level keys added/removed: %s / %s" % (top_added, top_removed))
    if set(case_changed) - ALLOWED_CASE:
        bad.append("case keys changed outside the cfg_rule: %s" % sorted(set(case_changed) - ALLOWED_CASE))
    if parms_changed or parms_added != list(GG.CTRL_KEYS):
        bad.append("parms: changed %s, added %s (only %s may be added)" % (parms_changed, parms_added, list(GG.CTRL_KEYS)))
    if set(bed_changed) - ALLOWED_BED or "groove" not in bed_changed:
        bad.append("bed keys changed outside the cfg_rule: %s" % bed_changed)
    if not (d["bed_order_kept"] and d["parms_order_kept"] and d["top_order_kept"]):
        bad.append("key order changed")
    d["ok"] = not bad
    d["bad"] = bad
    if bad:
        raise SystemExit("DG1 cfg key diff is not the cfg_rule list: %s" % bad)
    return d


def out_path(c):
    return os.path.join(GC.B50, c["out_root"], "ready", c["run_id"] + ".json").replace("\\", "/")


def write_cfg(c, force=False):
    p = out_path(c)
    rd = os.path.join(GC.B50, c["out_root"], c["run_id"])
    if os.path.exists(os.path.join(rd, "run.json")) or os.path.exists(os.path.join(rd, "chain.log")):
        raise SystemExit("%s already has a chain/run record: the cfg is not rewritten" % rd)
    b = dumps_file(c)
    if os.path.exists(p):
        old = open(p, "rb").read()
        if old == b:
            return p, "unchanged"
        if not force:
            raise SystemExit("%s exists with other content (sha16 %s); not overwritten without --force=1" % (p, hashlib.sha256(old).hexdigest()[:16]))
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "wb") as fh:
        fh.write(b)
    return p, "written"


