            print("  %s %s precheck ok %s particles %d written %s equal %s diff %s" % (k, v["run_id"], v["precheck_ok"], v["particles_model"], v["written"],
                                                                                    v["written_equal"], {kk: vv for kk, vv in v["key_diff"].items() if kk not in ("ok", "bad")}))
