def dirset(spec):
    """(theta deg, weight sum 1): a copy of flip52/dfg52_screen.dirset (the screen that chose the set; g52_pcfg compares the two bit for bit).
    ('hyb', centre, sigma, cap, nhalf): +-linspace(max(c - 2.5 s, 2), min(c + 2.5 s, cap), nhalf), w = exp(-(|th| - c)^2 / (2 s^2)) (plan E X2);
    ('cross', beta, sigma, n): linspace(-(b + 2.5 s), b + 2.5 s, n), two Gaussian lobes; ('uni', thmax, n)."""
    k = spec[0]
    if k == "cross":
        b, s, n = spec[1:]
        tm = min(b + 2.5 * s, 85.0)
        th = np.linspace(-tm, tm, int(n))
        w = np.exp(-0.5 * ((th - b) / s) ** 2) + np.exp(-0.5 * ((th + b) / s) ** 2)
    elif k == "uni":
        tm, n = spec[1:]
        th = np.linspace(-tm, tm, int(n)); w = np.ones(len(th))
    elif k == "hyb":
        c, s, cap, nh = spec[1:]
        t1 = np.linspace(max(c - 2.5 * s, 2.0), min(c + 2.5 * s, cap), int(nh))
        w1 = np.exp(-0.5 * ((t1 - c) / s) ** 2)
        th = np.concatenate([-t1[::-1], t1]); w = np.concatenate([w1[::-1], w1])
    else:
        raise ValueError(k)
    return th.astype(float), w / w.sum()


def freqset(P, ns, fw="eq"):
    """(omega, weight sum 1); 'eq' = equal weights (the frozen choice)."""
    f = np.asarray(ns, float) / float(P)
    if isinstance(fw, (list, tuple)):
        w = np.asarray(fw, float)
    elif fw == "eq":
        w = np.ones(len(f))
    else:
        raise ValueError(fw)
    return 2 * math.pi * f, w / w.sum()


