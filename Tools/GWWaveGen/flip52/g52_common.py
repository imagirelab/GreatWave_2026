# ------------------------------------------------------------------ the box (box48 with the top as a parameter: box48 fixes z_top +17 m)
def box52(dp, Lx=LX, W=W_MAIN, x0=0.0, zb=ZB, z_top=Z_TOP, floor_pad=2, side_pad=0):
    """g48_common.box48 / g46_common.box with the box top z_top as a parameter (the DFG tank's top is +20 m, box48's is +17 m).
    Lengths are rounded up to the grid (2 dp); the offsets o put the walls on grid faces (FLIP45 rule R1)."""
    dp = float(dp)
    vox = 2.0 * dp
    Lx_, nx = rup(float(Lx), vox)
    W_, nz = rup(float(W), vox)
    Hz, ny = rup(float(z_top) - float(zb), vox)
    b = dict(dp=dp, vox=vox, x0=float(x0), x1=float(x0) + Lx_, Lx=Lx_, W=W_, z_bottom=float(zb), z_top=float(zb) + Hz, Hz=Hz,
             floor_pad=int(floor_pad), z_floor=float(zb) - int(floor_pad) * vox,
             cells=[nx, nz + int(side_pad), ny + int(floor_pad)], side_pad=int(side_pad), y_side_low=-int(side_pad) * vox)
    b["ox"] = (0.5 * vox - float(x0)) % vox
    b["oy"] = (0.5 * vox - float(zb)) % vox
    b["oz"] = (0.5 * vox) % vox
    for k_ in ("x1", "Lx", "W", "z_top", "Hz", "ox", "oy", "oz"):
        if not is_binary_exact(abs(b[k_]) if b[k_] != 0 else 1.0):
            raise ValueError("box %s = %r is not binary exact" % (k_, b[k_]))
    return b


